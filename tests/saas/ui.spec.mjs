test('viewer cannot mutate and imported markup renders as text',async ({page,browser})=>{
  const origin='http://127.0.0.1:32901';
  const request=async (context,path,value)=>context.post(origin+path,{headers:{Origin:origin,'Idempotency-Key':crypto.randomUUID()},data:value});
  await request(page.request,'/api/auth/sign-up/email',{name:'Tenant Admin',email:'tenant-admin@example.invalid',password:'synthetic-admin-password-2026'});
  const org=await (await request(page.request,'/api/auth/organization/create',{name:'Viewer Team',slug:'viewer-team'})).json();
  const project=await (await request(page.request,'/api/saas/organizations/'+org.id+'/projects',{name:'Review Project'})).json();
  const sample=(await (await page.request.get(origin+'/saas-demo.json')).json()).traces[1];sample.name='<img src=x onerror="window.syntheticXss=true">';
  await request(page.request,'/api/saas/projects/'+project.id+'/import',{trace:sample,format:'generic'});
  const viewer=await browser.newContext({baseURL:origin});
  await request(viewer.request,'/api/auth/sign-up/email',{name:'Viewer Engineer',email:'viewer-ui@example.invalid',password:'synthetic-viewer-password-2026'});
  const me=await (await viewer.request.get(origin+'/api/saas/me')).json();
  const invite=await (await request(page.request,'/api/auth/organization/invite-member',{organizationId:org.id,email:'viewer-ui@example.invalid',role:'viewer'})).json();
  await request(viewer.request,'/api/auth/organization/accept-invitation',{invitationId:invite.id});
  await request(page.request,'/api/saas/projects/'+project.id+'/access',{user_id:me.user.id,enabled:true});
  const readOnly=await viewer.newPage();await readOnly.goto('/debugger.html#failures');
  await expect(readOnly.getByRole('button',{name:'Import trace',exact:true})).toHaveCount(0);
  await expect(readOnly.locator('tbody img')).toHaveCount(0);
  await expect(readOnly.getByText(sample.name,{exact:true})).toBeVisible();
  expect(await readOnly.evaluate(()=>window.syntheticXss)).toBeUndefined();
  await readOnly.getByRole('button',{name:'Billing',exact:true}).click();
  await expect(readOnly.getByRole('button',{name:'Choose Team · test mode'})).toBeDisabled();
  await viewer.close();
});

async function inspectPlanning(page){
  await page.setViewportSize({width:1440,height:1000});
  const origin='http://127.0.0.1:32901',post=(path,data)=>page.request.post(origin+path,{headers:{Origin:origin,'Idempotency-Key':crypto.randomUUID()},data});
  const org=await (await post('/api/auth/organization/create',{name:'Planning Team',slug:'planning-team'})).json();
  const p=await (await post('/api/saas/organizations/'+org.id+'/projects',{name:'Planning Project'})).json();
  const trace=await (await page.request.get(origin+'/planning-demo.json')).json();
  const imported=await post('/api/saas/projects/'+p.id+'/import',{trace,format:'native'});expect(imported.status()).toBe(200);
  await page.goto('/debugger.html#failures');
  await page.reload();
  await page.getByLabel('Organization',{exact:true}).selectOption(org.id);
  await expect(page.getByLabel('Project',{exact:true})).toHaveValue(p.id);
  await page.getByRole('button',{name:'Inspect',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Predictive planning decisions'})).toBeVisible();
  await page.locator('dialog [data-planning-decision]').first().locator('summary').first().click();
  await expect(page.getByRole('heading',{name:'Actual observation',exact:true}).first()).toBeVisible();
  await expect(page.getByRole('heading',{name:'Predicted first observation',exact:true}).first()).toBeVisible();
  await page.locator('[data-planning-filter]').selectOption('errors');
  const visible=page.locator('[data-planning-decision]:not([hidden])');
  expect(await visible.count()).toBeGreaterThan(0);
  if(!await visible.first().evaluate(node=>node.open))await visible.first().locator('summary').first().click();
  await page.screenshot({path:'.replay/ui-results/planning-decision.png',fullPage:true});
  await page.getByRole('button',{name:'×'}).click();
}
