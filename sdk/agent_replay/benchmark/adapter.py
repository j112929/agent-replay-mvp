"""Adapters own environment internals and evaluation; the runner owns lifecycle."""
from typing import Any, Protocol
from .contracts import BenchmarkTask, BenchmarkResult


class BenchmarkAdapter(Protocol):
    name: str

    def load_tasks(self) -> list[BenchmarkTask]: ...
    def prepare_environment(self, task: BenchmarkTask, capture: Any) -> Any: ...
    def final_state(self, task: BenchmarkTask, environment: Any) -> Any: ...
    def evaluate(self, task: BenchmarkTask, trajectory: dict, final_state: Any) -> BenchmarkResult: ...
    def cleanup(self) -> None: ...
